# ---- DB helper: snap points to stream in their subcatchment (shared) ----
# conn: a real DBI connection (NOT the pool)
# points_table: DBI::Id(schema="shiny_user", table="points_<uuid>")
# progress: optional function(pct) to report progress (0..100)
# Returns: invisible(TRUE). Updates DB table in-place.
snap_points_subcatchment_db <- function(conn, points_table, progress = NULL) {

  progress <- progress %||% function(...) invisible(NULL)

  # Ensure schema exists (now includes geom_* AND derived columns)
  ensure_points_schema(conn, points_table)

  pt_q <- DBI::dbQuoteIdentifier(conn, points_table)

  progress(40)

  # 3) reg_id  (CHANGED: hint can move points across regions)
  reg_q <- DBI::dbQuoteIdentifier(conn, DBI::Id(schema = "hydro", table = "regional_units"))
  DBI::dbExecute(conn, paste0(
    "UPDATE ", pt_q, " poi
        SET reg_id = reg.reg_id
       FROM ", reg_q, " reg
      WHERE ST_Intersects(COALESCE(poi.geom_hint, poi.geom_orig), reg.geom)"
  ))
  progress(60)

  # 4) hylak_id (CHANGED: hint can move points into/out of lakes)
  lak_q <- DBI::dbQuoteIdentifier(conn, DBI::Id(schema = "hydro", table = "hydrolakes_poly"))
  DBI::dbExecute(conn, paste0(
    "UPDATE ", pt_q, " poi
        SET hylak_id = lak.hylak_id
       FROM ", lak_q, " lak
      WHERE ST_Intersects(COALESCE(poi.geom_hint, poi.geom_orig), lak.geom)"
  ))
  progress(72)

  # 5) subc_id + basin_id (CHANGED: sub-catchment follows the hint when present)
  subc_q <- DBI::dbQuoteIdentifier(conn, DBI::Id(schema = "hydro", table = "sub_catchments"))
  DBI::dbExecute(conn, paste0(
    "UPDATE ", pt_q, " poi SET
           subc_id  = sub.subc_id,
           basin_id = sub.basin_id
      FROM ", subc_q, " sub
     WHERE ST_Intersects(COALESCE(poi.geom_hint, poi.geom_orig), sub.geom)
       AND poi.reg_id = sub.reg_id"
  ))
  progress(85)

  # 6) Snap to segment within (new) subcatchment
  seg_q <- DBI::dbQuoteIdentifier(conn, DBI::Id(schema = "hydro", table = "stream_segments"))
  DBI::dbExecute(conn, paste0(
    "UPDATE ", pt_q, " poi SET
         strahler_order = seg.strahler,
         geom_snap = ST_LineInterpolatePoint(
           seg.geom,
           ST_LineLocatePoint(seg.geom, COALESCE(poi.geom_hint, poi.geom_orig))
         ),
         snap_state = 'snapped',
         snap_fail_reason = NULL
    FROM ", seg_q, " seg
    WHERE seg.subc_id = poi.subc_id"
  ))

  # Mark failures (no snapped geometry produced)
  # TODO: add a better explanation for the failed snapping attempt
  # there is always a segment in a sub-catchment, but the point may be outside
  # of any sub-catchment
  DBI::dbExecute(conn, paste0(
    "UPDATE ", pt_q, "
        SET snap_state = 'failed',
            snap_fail_reason = 'no segment in subcatchment'
      WHERE geom_snap IS NULL"
  ))
  progress(95)

  # Build a clean base name for the spatial index (63-char limit)
  idx_base <- if (inherits(points_table, "Id")) {
    nm <- points_table@name
    if (!is.null(names(nm)) && "table" %in% names(nm)) nm[["table"]] else tail(nm, 1)
  } else {
    as.character(points_table)
  }

  # Add a spatial index for geom_snap
  idx_name_snap <- substr(paste0(idx_base, "_geom_snap_idx"), 1, 63)
  idx_snap_q <- DBI::dbQuoteIdentifier(conn, idx_name_snap)

  DBI::dbExecute(conn, paste0(
    "CREATE INDEX IF NOT EXISTS ", idx_snap_q,
    " ON ", pt_q, " USING GIST (geom_snap)"
  ))

  DBI::dbExecute(conn, paste0("ANALYZE ", pt_q))

  progress(100)
  invisible(TRUE)
}


snap_points_strahler_db <- function(
    conn,
    points_table,
    target_strahler,
    search_radius_m = 500,
    progress = NULL
) {
  progress <- progress %||% function(...) invisible(NULL)

  # MB: search_radius_m is ignored!

  # Ensure schema exists (now includes geom_* AND derived columns)
  ensure_points_schema(conn, points_table)

  # This is the database name
  pt_q <- DBI::dbQuoteIdentifier(conn, points_table)

  # (1) Add required columns to the table
  DBI::dbExecute(conn, paste0(
    "ALTER TABLE ", pt_q, "
       ADD COLUMN IF NOT EXISTS geog_closest geography(LINESTRING, 4326),
       ADD COLUMN IF NOT EXISTS subcid_closest integer,
       ADD COLUMN IF NOT EXISTS basinid_closest integer,
       ADD COLUMN IF NOT EXISTS strahler_closest integer"
  ))

  progress(5)

  # (2) Get those regional unit ids which are in a buffer of 5 degrees
  # around the points
  # WHERE ST_DWithin(reg.geom, temp.geom_orig, ", as.character(buffer_size_degrees), ")
  buffer_size_degrees <- 5
  reg_ids_df <- DBI::dbGetQuery(conn, paste0(
    "SELECT DISTINCT candidate_regions.reg_id
     FROM ", pt_q, " AS temp
     CROSS JOIN LATERAL (
	SELECT reg_id
	FROM hydro.regional_units reg
        WHERE ST_DWithin(reg.geom, COALESCE(temp.geom_hint, temp.geom_orig), ", as.character(buffer_size_degrees), ")
     ) AS candidate_regions"
  ))
  reg_ids_int = reg_ids_df$reg_id
  reg_ids_str = paste0(reg_ids_int, collapse=", ")

  progress(10)

  # (3) Store the closest neighbours (stream segments!!)
  # These are the stream segments we will snap to!
  # so subcid_closest is the new subc_id
  min_strahler <- target_strahler
  DBI::dbExecute(conn, paste0(
    "UPDATE ", pt_q, " AS temp1
     SET
       geog_closest = closest.geog,
       strahler_closest = closest.strahler,
       subcid_closest = closest.subc_id,
       basinid_closest = closest.basin_id
     FROM ", pt_q, " AS temp2
     CROSS JOIN LATERAL (
       SELECT seg.geog, seg.strahler, seg.subc_id, seg.basin_id
       FROM stream_segments seg
       WHERE seg.strahler >= ", as.character(min_strahler), "
       AND reg_id = ANY (ARRAY[", reg_ids_str, "])
       ORDER BY seg.geog <->  COALESCE(temp2.geom_hint, temp2.geom_orig)::geography
       LIMIT 1
     ) AS closest
     WHERE temp1.geom_orig = temp2.geom_orig"
  ))

  progress(90)

  # (4) Store the snapped points in temp:
  DBI::dbExecute(conn, paste0(
    "UPDATE ", pt_q, " AS temp
    SET geom_snap = ST_LineInterpolatePoint(
      temp.geog_closest::geometry,
      ST_LineLocatePoint(temp.geog_closest::geometry, COALESCE(temp.geom_hint, temp.geom_orig))
    ),
    snap_state = 'snapped',
    snap_fail_reason = NULL,
    strahler_order = temp.strahler_closest,
    subc_id = temp.subcid_closest,
    basin_id = temp.basinid_closest"
  ))
  progress(95)

  # (5) Mark failures (no snapped geometry produced)
  # TODO: Not sure whether points can stay unsnapped with this method,
  # and what might be possible reasons.
  DBI::dbExecute(conn, paste0(
    "UPDATE ", pt_q, "
        SET snap_state = 'failed',
            snap_fail_reason = 'unknown'
      WHERE geom_snap IS NULL"
  ))

  # Build a clean base name for the spatial index (63-char limit)
  idx_base <- if (inherits(points_table, "Id")) {
    nm <- points_table@name
    if (!is.null(names(nm)) && "table" %in% names(nm)) nm[["table"]] else tail(nm, 1)
  } else {
    as.character(points_table)
  }

  # Add a spatial index for geom_snap
  idx_name_snap <- substr(paste0(idx_base, "_geom_snap_idx"), 1, 63)
  idx_q_snap <- DBI::dbQuoteIdentifier(conn, idx_name_snap)

  DBI::dbExecute(conn, paste0(
    "CREATE INDEX IF NOT EXISTS ", idx_snap_q,
    " ON ", pt_q, " USING GIST (geom_snap)"
  ))

  DBI::dbExecute(conn, paste0("ANALYZE ", pt_q))

  progress(100)
  invisible(TRUE)
}


# Read lakes for points
read_lakes_for_points_db <- function(conn, points_table) {
  pt_q <- DBI::dbQuoteIdentifier(conn, points_table)
  hl_q <- DBI::dbQuoteIdentifier(conn, DBI::Id(schema = "hydro", table = "hydrolakes_poly"))
  li_q <- DBI::dbQuoteIdentifier(conn, DBI::Id(schema = "hydro", table = "lake_intersections"))

  DBI::dbGetQuery(conn, paste0(
    "SELECT poi.id, poi.hylak_id,
            hylak.lake_name AS hydrolake_name, hylak.lake_area AS hydrolake_area,
            lak.subc_id AS outlet_subc_id,
            round(lak.latitude::numeric, 6) AS outlet_latitude,
            round(lak.longitude::numeric, 6) AS outlet_longitude
       FROM ", pt_q, " poi
       JOIN ", hl_q, " hylak
         ON poi.hylak_id = hylak.hylak_id
       JOIN ", li_q, " lak
         ON poi.hylak_id = lak.hylak_id
        AND poi.reg_id = lak.reg_id
      WHERE lak.outlet_id = 1"
  ))
}

# Use this function to update the point table in the database when all points are
# deleted in the point editor
wipe_points_db <- function(conn, points_table) {
  ensure_points_schema(conn, points_table)
  pt_q <- DBI::dbQuoteIdentifier(conn, points_table)

  # delete all rows (and reset identity if you rely on it)
  DBI::dbExecute(conn, paste0("TRUNCATE TABLE ", pt_q, " RESTART IDENTITY"))

  DBI::dbExecute(conn, paste0("ANALYZE ", pt_q))
  invisible(TRUE)
}
