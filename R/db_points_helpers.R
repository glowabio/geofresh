    stop("Invalid id(s): must be whole numbers. Bad row(s): ", paste(head(bad, 20), collapse = ", "))
  }

  # Use character ids for interpolation, and cast to bigint in SQL for exact matching
  df_hint$id_chr <- format(id_num, scientific = FALSE, trim = TRUE)

  # TODO: execute UPDATE only once for all rows with changed marker positions
